// Turns bookmarklet/bookmarklet.js into web/bookmarklet-href.js (a javascript: URL the ABOUT tab uses as a link).
// Plain text work, no tools: drop lines that start with //, join the rest, URL-encode. A test fails if the output is stale.
// Run: node scripts/build-bookmarklet.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

export function bookmarkletHref(source) {
  const code = source.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith('//')).join(' ');
  return `javascript:${encodeURI(code)}`;
}

export function expectedOutput() {
  const href = bookmarkletHref(readFileSync(`${ROOT}bookmarklet/bookmarklet.js`, 'utf8'));
  return `// Generated by scripts/build-bookmarklet.mjs from bookmarklet/bookmarklet.js. Do not edit by hand.\nexport const BOOKMARKLET_HREF = ${JSON.stringify(href)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(`${ROOT}web/bookmarklet-href.js`, expectedOutput());
  console.log('wrote web/bookmarklet-href.js');
}
